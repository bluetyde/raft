"""Tests for validation/m7_heat_transfer.py on a synthetic library whose measured data come from a known law.

The real libraries are never evaluated here: the comparison is run once, as the protocol says.
"""
from __future__ import annotations

import unittest

from validation import m7_heat_transfer as ht
from validation import m7_power_ascension as base
from validation.tests.test_m7_power_ascension import synthetic_lib

P = [0.09, 2.93, 43.6, 100.3, 188.9, 223.0, 250.0, 191.1, 103.7, 47.5, 0.29]
T0 = 25.8 + base.K0


def synthetic_measured(lib, h0, n, peaking=1.5, rising=False):
    """Measured data generated by the law itself (and a hot-element temperature `peaking` times the mean rise)."""
    rows = ht.law_states(lib, P, T0, rising, h0, n)
    t_mean = [r["tFuelK"] for r in rows]
    return {
        "defectPcm": [r["defectPcm"] for r in rows],
        "fuelTempC": [25.8 + peaking * (t - t_mean[0]) for t in t_mean],
        "fuelTempC_table2_first_row": 25.8,
        "pCalculatedKW": P,
        "pIndicatedKW": P,
        "peakIndex": 6,
    }


class Law(unittest.TestCase):
    def test_closed_form_satisfies_the_heat_balance_and_n_zero_is_the_shipped_law(self):
        h0, n, p_w = 2000.0, 0.25, 100e3
        dt = ht.delta_t(p_w, h0, n)
        self.assertAlmostEqual(h0 * (dt / ht.DT_REF) ** n * dt, p_w, delta=1e-6 * p_w)
        lib = synthetic_lib()
        for a, b in zip(ht.law_states(lib, P, T0, True, 3000.0, 0.0), base.model_states(lib, P, T0, True, 3000.0)):
            self.assertAlmostEqual(a["tFuelK"], b["tFuelK"], places=9)
            self.assertAlmostEqual(a["defectPcm"], b["defectPcm"], places=9)


class Calibration(unittest.TestCase):
    def test_the_fit_recovers_a_known_law(self):
        lib = synthetic_lib()
        meas = synthetic_measured(lib, 2000.0, 0.25)
        targets = {s: meas["defectPcm"][s - 1] for s in ht.CALIBRATION}
        h0, n = ht.calibrate_law(lib, P, T0, False, targets)
        self.assertAlmostEqual(n, 0.25, places=4)
        self.assertAlmostEqual(h0, 2000.0, delta=0.5)

    def test_the_constant_refit_recovers_a_constant_law(self):
        lib = synthetic_lib()
        meas = synthetic_measured(lib, 1800.0, 0.0)
        targets = {s: meas["defectPcm"][s - 1] for s in ht.CALIBRATION}
        self.assertAlmostEqual(ht.refit_constant_hA(lib, P, T0, False, targets), 1800.0, delta=0.5)

    def test_no_solution_is_reported_not_invented(self):
        flat = synthetic_lib(alpha_fuel_pcm_per_k=0.0, alpha_cool_pcm_per_k=0.0)
        self.assertIsNone(ht.calibrate_law(flat, P, T0, False, {3: 300.0, 7: 1400.0}))


class Metrics(unittest.TestCase):
    def test_state_tolerance_is_ten_percent_or_eight_pcm_whichever_is_larger(self):
        self.assertEqual(ht.label_state_defect(110.0, 100.0), "good")
        self.assertEqual(ht.label_state_defect(28.0, 20.6), "good")          # 7.4 pcm: inside the 8 pcm floor
        self.assertEqual(ht.label_state_defect(35.0, 20.6), "plausible")     # 14.4 pcm: inside 20 pcm
        self.assertEqual(ht.label_state_defect(45.0, 20.6), "fails")
        self.assertEqual(ht.label_state_defect(1100.0, 1000.0), "good")
        self.assertEqual(ht.label_state_defect(1240.0, 1000.0), "plausible")
        self.assertEqual(ht.label_state_defect(1260.0, 1000.0), "fails")

    def test_end_to_end_on_data_from_a_known_law(self):
        lib = synthetic_lib()
        meas = synthetic_measured(lib, 2000.0, 0.25, peaking=1.5)
        out = ht.evaluate_case(lib, meas, T0, P, False)
        l1, l0 = out["L1"], out["L0"]
        self.assertAlmostEqual(l1["n"], 0.25, places=3)
        self.assertTrue(l1["nPhysical"])
        self.assertEqual(l1["A2"]["label"], "good")
        self.assertLess(l1["C2"]["maxAbsDiff"], 1e-6)
        self.assertEqual((l1["X"]["defect"], l1["X"]["tempShape"]), ("good", "good"))
        self.assertAlmostEqual(l1["E"]["peakingFactor"], 1.5, places=4)
        # a constant hA cannot follow dT ~ P^0.8: its temperature shape is visibly off
        self.assertGreater(l0["C2"]["maxAbsDiff"], 0.05)
        self.assertEqual(len(l1["returnLeg"]), 3)


class Decision(unittest.TestCase):
    @staticmethod
    def summary(l1_c2=0.02, l0_c2=0.11, a2="good", n_ok=True, x="good", l0_a2="good"):
        l1 = {"computed": True, "A2": {"worst": a2, "best": a2}, "C2": {"maxAbsDiff": l1_c2, "worst": base.label_diff("C", l1_c2), "best": base.label_diff("C", l1_c2)},
              "X": {"defectWorst": x, "tempShapeWorst": x}, "E": {"min": 1.4, "max": 1.6}, "N": {"min": 0.2, "max": 0.3, "allPhysical": n_ok}}
        l0 = {"computed": True, "A2": {"worst": l0_a2, "best": l0_a2}, "C2": {"maxAbsDiff": l0_c2, "worst": base.label_diff("C", l0_c2), "best": base.label_diff("C", l0_c2)},
              "X": {"defectWorst": "good", "tempShapeWorst": "good"}, "E": {"min": 1.0, "max": 1.0}}
        return {"L0": l0, "L1": l1}

    def test_the_adoption_rule(self):
        self.assertTrue(ht.adoption(self.summary())["adopt"])
        # not at least twice as good in the temperature shape
        self.assertIn("not an improvement over a constant hA refitted on the same states", ht.adoption(self.summary(l1_c2=0.07, l0_c2=0.11))["reasons"])
        # a non-physical exponent blocks adoption whatever the other labels say
        self.assertFalse(ht.adoption(self.summary(n_ok=False))["adopt"])
        # a failing extrapolation blocks it too
        self.assertFalse(ht.adoption(self.summary(x="fails"))["adopt"])
        # a held-out defect that fails blocks it
        self.assertFalse(ht.adoption(self.summary(a2="fails"))["adopt"])

    def test_the_run_has_the_documented_shape(self):
        lib = synthetic_lib()
        meas = synthetic_measured(lib, 2000.0, 0.25)
        report = ht.run({"syn": lib}, meas)
        entry = report["libraries"]["syn"]
        self.assertEqual(len(entry["cases"]), 8)                       # 2 T0 x 2 power axes x 2 pool cases
        self.assertEqual(set(entry["summary"]), {"L0", "L1"})
        self.assertIn("adopt", entry["adoption"])
        self.assertIn("adoptAsCandidate", report)


if __name__ == "__main__":
    unittest.main()
