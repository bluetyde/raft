"""Tests for validation/m7_hot_element.py on a synthetic library with known peaking, conduction constants and an adiabatic pulse.

The real libraries are only loaded (a smoke test); the comparison on the real pulse database is run once, as the protocol says.
"""
from __future__ import annotations

import math
import unittest
from types import SimpleNamespace

from physics_ref.library import Table
from validation import m7_hot_element as he
from validation import m7_power_ascension as base
from validation.tests.test_m7_heat_transfer import P, T0
from validation.tests.test_m7_power_ascension import synthetic_lib

EDGES = [-19.05, -1.27, 1.27, 19.05]                  # heights 17.78, 2.54, 17.78; the centre bin is the middle one
ELEMENTS = ["B1", "B2", "C1", "C2"]
H = [EDGES[i + 1] - EDGES[i] for i in range(3)]


def lib_with_shapes(cp=300.0, mass=100.0):
    """Synthetic library: 3 powered elements (B1 peaked at the centre, B2 flat, C1) and C2 unpowered."""
    lib = synthetic_lib()
    lib.fuel_cp = Table([200.0, 1500.0], [cp, cp])
    lib.fuel_mass = mass
    lib.fuel_fraction = 1.0
    frac = [  # element-major, (e, a)
        0.10, 0.20, 0.10,      # B1: 0.4 of the power, peaked at the centre bin
        0.10, 0.01, 0.10,      # B2: hotter in its wide end bins
        0.10, 0.05, 0.10,      # C1  (sum 1.05 - normalisation is not needed by the factors)
        0.0, 0.0, 0.0,         # C2: no power
    ]
    n = len(frac)
    lib.shapes = {"bins": {"elements": ELEMENTS, "axialEdgesCm": EDGES}, "base": "base",
                  "rodDeltas": {"safety": {"x": [0.0, 1.0], "array": "zero2"}}, "tempDelta": {"T": [294.0, 800.0], "array": "tdelta"}}
    lib.arrays = {"base": frac, "zero2": [0.0] * (2 * n), "tdelta": [0.0] * n + [0.0, 0.1, 0.0] + [0.0] * (n - 3)}
    lib.rod_by_id = {"regulating": lib.rod_by_id["regulating"], "safety": SimpleNamespace(worth=Table([0.0, 1.0], [0.0, 0.0]))}
    return lib


def record(core, tmax1, tmax2, energy, **kw):
    return SimpleNamespace(core_config=core, t1_max_c=tmax1, t2_max_c=tmax2, energy_1000pts_mws=energy, energy_1pct_mws=kw.get("e1"),
                           energy_tangent_mws=kw.get("e2"))


def pulses_from(f_tc, lib, core="242", n=6, t0=25.0):
    """Records generated by adiabatic heating at peaking f_tc, with the library's constant cp."""
    out = []
    for i in range(n):
        e_mws = 5.0 + i
        rise = f_tc * e_mws * 1e6 / (lib.fuel_mass * 300.0)
        out.append(record(core, t0 + rise, t0 + rise * 1.02, e_mws, e1=e_mws, e2=e_mws))
    return out


class Conduction(unittest.TestCase):
    def test_mean_conduction_coefficient_matches_the_closed_form(self):
        ri, ro = he.RI, he.RO
        integral_a = ro**2 * (ro**2 - ri**2) / 2 - (ro**4 - ri**4) / 4
        integral_b = 2 * ri**2 * (ro**2 / 4 - (ri**2 / 2 * math.log(ro / ri) + ri**2 / 4))
        exact = 2.0 / (ro**2 - ri**2) * (integral_a - integral_b) / 4.0
        self.assertAlmostEqual(he.c_mean(), exact, places=6)
        self.assertGreater(he.c_of_r(he.RI), he.c_mean())          # the inner wall is the hottest radius
        self.assertAlmostEqual(he.c_of_r(he.RO), 0.0, places=12)


class Stage1(unittest.TestCase):
    def test_f_tc_is_recovered_from_adiabatic_pulses_and_a_small_sample_is_not_computed(self):
        lib = lib_with_shapes()
        s1 = he.stage1(pulses_from(1.7, lib), lib, "242")
        got = s1["primary"]["both"]["median"]
        self.assertAlmostEqual(got, 1.7 * 1.01, delta=1e-9)         # tc2 reads 2 % above tc1: the median of both is halfway
        s1 = he.stage1(pulses_from(1.7, lib, n=2) + pulses_from(3.0, lib, core="246"), lib, "242")
        self.assertIsNone(s1["primary"]["both"]["median"])
        self.assertEqual(s1["coreConfigCounts"], {"242": 2, "246": 6})

    def test_only_an_empty_field_or_a_zero_energy_drops_a_pulse(self):
        lib = lib_with_shapes()
        recs = pulses_from(1.7, lib, n=5) + [record("242", 80.0, None, 0.0), record("242", None, None, 5.0), record("242", 60.0, 70.0, None)]
        v = he.pulse_peakings(recs, lib, "242", "energy_1000pts_mws", 25.0)
        self.assertEqual((len(v["t1"]), len(v["t2"])), (5, 5))


class Stage2(unittest.TestCase):
    def test_peaking_of_the_centre_and_hottest_bins(self):
        lib = lib_with_shapes()
        sp = he.shape_peakings(lib, {"safety": 1.0, "regulating": 0.5}, 294.0)
        self.assertEqual((sp["elementsWithPower"], sp["centreBin"]), (3, 1))
        n_l = 3 * he.L_CM
        self.assertAlmostEqual(sp["B"]["B1"]["centre"], 0.20 / H[1] * n_l, places=9)
        self.assertAlmostEqual(sp["B"]["B2"]["centre"], 0.01 / H[1] * n_l, places=9)
        self.assertAlmostEqual(sp["B"]["B2"]["hottest"], 0.10 / H[0] * n_l, places=9)     # B2 is hotter in its wide end bins
        self.assertEqual(he.primary_element(sp), "B1")

    def test_the_temperature_delta_is_interpolated_into_the_shape(self):
        lib = lib_with_shapes()
        cold = he.shape_array(lib, {"safety": 1.0}, 294.0)
        warm = he.shape_array(lib, {"safety": 1.0}, 547.0)                  # halfway up the table
        self.assertAlmostEqual(warm[1] - cold[1], 0.05, places=9)           # the delta sits in B1's middle bin
        self.assertAlmostEqual(warm[4] - cold[4], 0.0, places=12)


class Chain(unittest.TestCase):
    def test_a_peaking_of_one_and_infinite_conductivity_gives_the_mean_rise(self):
        pool = [300.0] * len(P)
        t = he.chain_temperatures(P, pool, 2000.0, 0.25, 1.0, 1e9, he.RI, 61)
        self.assertAlmostEqual(t[6] - 300.0, ht_dt(250.0, 2000.0, 0.25), places=4)

    def test_end_to_end_on_data_the_chain_itself_made(self):
        lib = lib_with_shapes()
        h0, n, f, k = 2000.0, 0.25, 1.6, he.K_PRIMARY
        pool = base.pool_temperatures(len(P), T0, False)
        t = he.chain_temperatures(P, pool, h0, n, f, k, he.RI, 61)
        meas = {"fuelTempC": [x - base.K0 for x in t], "defectPcm": [0.0] * 6 + [1.0e3] + [0.0] * 4, "peakIndex": 6}
        m = he.rise_ratio_and_shape(meas, t)
        self.assertAlmostEqual(m["ratio"], 1.0, places=9)
        self.assertLess(m["h2MaxDiff"], 1e-12)
        # a hotter thermocouple is reported high; metric R scales the mean rise back down to the measured one
        hot = he.chain_temperatures(P, pool, h0, n, 1.3 * f, k, he.RI, 61)
        self.assertGreater(he.rise_ratio_and_shape(meas, hot)["ratio"], 1.0)
        r = he.implied_coefficient(lib, {**meas, "defectPcm": [0.0] * 6 + [1000.0] + [0.0] * 4}, P, T0, False, h0, n, 1.3 * f, k, he.RI, 61)
        self.assertLess(r["scale"], 1.0)
        back = he.chain_temperatures(P, pool, h0, n, 1.3 * f, k, he.RI, 61, r["scale"])
        self.assertAlmostEqual(back[6] - back[0], t[6] - t[0], places=6)


def ht_dt(p_kw, h0, n):
    from validation import m7_heat_transfer as ht
    return ht.delta_t(p_kw * 1e3, h0, n)


class Decision(unittest.TestCase):
    @staticmethod
    def entry(median=1.7, g=("good", 1.0), hs=("fails", 1.6), hp=("good", 1.0)):
        return {"stage1": {"primary": {"both": {"median": median}}}, "G": {"primary": {"label": g[0], "ratio": g[1]}},
                "H1shape": {"primary": {"label": hs[0], "ratio": hs[1]}}, "H1pulse": {"primary": {"label": hp[0], "ratio": hp[1]}}}

    def test_the_four_branches(self):
        self.assertEqual(he.decide(self.entry())["case"], 1)
        self.assertEqual(he.decide(self.entry(g=("fails", 0.5), hs=("good", 1.0)))["case"], 2)
        self.assertEqual(he.decide(self.entry(g=("fails", 2.0), hs=("fails", 1.6), hp=("fails", 1.6)))["case"], 3)
        self.assertEqual(he.decide(self.entry(median=None))["case"], 3)
        self.assertIsNone(he.decide(self.entry(hs=("good", 1.0)))["case"])
        self.assertEqual([he.label_ratio(r) for r in (0.85, 1.15, 0.7, 1.4, 0.69, 1.41)], ["good", "good", "plausible", "plausible", "fails", "fails"])

    def test_the_full_run_on_a_synthetic_library_has_the_documented_shape(self):
        lib = lib_with_shapes()
        pool = base.pool_temperatures(len(P), T0, False)
        t = he.chain_temperatures(P, pool, 2000.0, 0.25, 1.5, he.K_PRIMARY, he.RI, 61)
        rows = ht_rows(lib)
        meas = {"states": [{"regulatingRodStep": 500}] * 11, "pCalculatedKW": P, "pIndicatedKW": P, "fuelTempC": [x - base.K0 for x in t],
                "fuelTempC_table2_first_row": 25.8, "defectPcm": [r["defectPcm"] for r in rows]}
        report = he.run({"core242": lib}, pulses_from(1.7, lib), meas)
        e = report["libraries"]["core242"]
        self.assertEqual(len(e["cases"]), 8)
        for key in ("G", "H1pulse", "H1shape", "decision", "stage1"):
            self.assertIn(key, e)
        self.assertIn("worst", e["H1shape"]["sensitivities"])


def ht_rows(lib):
    from validation import m7_heat_transfer as ht
    return ht.law_states(lib, P, T0, False, 2000.0, 0.25)


class RealLibrariesLoad(unittest.TestCase):
    def test_the_shape_arrays_have_the_b_ring_and_the_expected_size(self):
        for name, path in base.LIBRARIES.items():
            lib = base.load_library(path)
            s = lib.shapes
            n = len(s["bins"]["elements"]) * (len(s["bins"]["axialEdgesCm"]) - 1)
            for b in ("B1", "B6"):
                self.assertIn(b, s["bins"]["elements"], name)
            self.assertEqual(len(lib.arrays[s["base"]]), n, name)
            self.assertEqual(len(he.shape_array(lib, {r: 1.0 for r in lib.rod_by_id}, 400.0)), n, name)


